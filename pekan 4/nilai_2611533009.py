# Program konversi nilai angka menjadi huruf

nilai = int(input("inputkan angka= "))

if nilai >= 81:
    print("A")
elif nilai >= 70:
    print("B")
elif nilai >= 60:
    print("C")
elif nilai >= 50:
    print("D")
else:
    print("E")